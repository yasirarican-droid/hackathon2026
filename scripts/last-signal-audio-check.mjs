import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const stories = JSON.parse(await readFile('public/content/final-signals.json', 'utf8'));
const records = JSON.parse(await readFile('public/content/narration.json', 'utf8')).recordings;
const base = process.env.STARBOARD_URL || 'http://127.0.0.1:4186/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
async function seek(page, seconds, duration) {
  await page.locator('.signal-seek').evaluate((e, value) => { e.value = String(value); e.dispatchEvent(new Event('input', { bubbles: true })); }, Math.round(seconds / duration * 1000));
}
try {
  const p = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  p.on('pageerror', error => errors.push(error.message));
  await p.goto(base);
  await p.locator('#application').waitFor({ state: 'visible', timeout: 60000 });
  for (const mission of ['apollo', 'viking', 'sojourner']) {
    const spec = stories[mission];
    await p.locator('.' + mission + '-card .mission-button').click();
    await p.locator('.telephone').click();
    const voice = p.locator('.signal-voice');
    await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .15);
    assert.equal(await voice.evaluate(e => e.muted), false);
    const duration = await voice.evaluate(e => e.duration);
    assert.ok(Math.abs(duration - spec.audio.durationSeconds) < .2);
    const record = records.find(r => r.file === spec.audio.file);
    assert.equal(await voice.evaluate(async e => [...new Uint8Array(await crypto.subtle.digest('SHA-256', await (await fetch(e.src)).arrayBuffer()))].map(x => x.toString(16).padStart(2, '0')).join('')), record.sha256);
    await p.getByRole('button', { name: 'Pause', exact: true }).click();
    assert.equal(await voice.evaluate(e => e.paused), true);
    const frozen = await voice.evaluate(e => e.currentTime);
    await p.waitForTimeout(250);
    assert.ok(Math.abs(await voice.evaluate(e => e.currentTime) - frozen) < .05);
    await seek(p, spec.audio.paragraphs[1].start + 1, duration);
    assert.equal(await p.locator('.signal-counter').innerText(), '2 / 4');
    assert.equal(await p.locator('.signal-text').innerText(), spec.paragraphs[1]);
    await p.getByRole('button', { name: 'Next →', exact: true }).click();
    assert.ok(Math.abs(await voice.evaluate(e => e.currentTime) - spec.audio.paragraphs[2].start) < .1);
    assert.equal(await p.locator('.signal-counter').innerText(), '3 / 4');
    assert.equal(await voice.evaluate(e => e.paused), true);
    await p.getByRole('button', { name: 'Toggle Last Signal narration and static sound', exact: true }).click();
    assert.equal(await voice.evaluate(e => e.muted), true);
    await p.getByRole('button', { name: 'Toggle Last Signal narration and static sound', exact: true }).click();
    assert.equal(await voice.evaluate(e => e.muted), false);
    await p.getByRole('button', { name: 'Resume', exact: true }).click();
    await p.waitForFunction(() => !document.querySelector('.signal-voice').paused);
    if (mission === 'apollo') {
      await p.evaluate(() => { window.oldSignalVoice = document.querySelector('.signal-voice'); });
      await p.keyboard.press('Escape');
      await p.waitForFunction(() => window.oldSignalVoice.paused && !window.oldSignalVoice.getAttribute('src'));
      await p.locator('.telephone').click();
      await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .1);
      await p.getByRole('button', { name: 'Skip to timeline →', exact: true }).click();
      await p.waitForURL(/#home$/);
      assert.equal(await p.evaluate(() => JSON.parse(localStorage.getItem('nasa-starboard-learning-v1')).screens.includes('apollo-signal')), false);
      await p.locator('.apollo-card .mission-button').click();
      await p.locator('.telephone').click();
      await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .1);
    }
    await p.getByRole('button', { name: 'Pause', exact: true }).click();
    await seek(p, duration - .35, duration);
    assert.equal(await p.locator('.signal-counter').innerText(), '4 / 4');
    assert.equal(await p.locator('.signal-text').innerText(), spec.paragraphs[3]);
    await p.waitForTimeout(450);
    assert.equal(await p.locator('.signal-ending').count(), 0);
    await p.screenshot({ path: 'docs/qa/last-signal-voice-' + mission + '.png' });
    await p.getByRole('button', { name: 'Resume', exact: true }).click();
    await p.locator('.signal-ending').waitFor();
    assert.equal(await voice.evaluate(e => e.ended), true);
    await p.waitForURL(/#home$/);
    assert.equal(await p.evaluate(m => JSON.parse(localStorage.getItem('nasa-starboard-learning-v1')).screens.includes(m + '-signal'), mission), true);
  }
  await p.locator('.sojourner-card .mission-button').click();
  await p.locator('.guide-fact').click();
  await p.waitForFunction(() => document.querySelector('.naming-story-audio')?.currentTime > .1);
  assert.ok(Math.abs(await p.locator('.naming-story-audio').evaluate(e => e.duration) - 41.247) < .2);
  assert.match(await p.locator('.naming-story-copy').innerText(), /Valerie Ambroise/);
  await p.evaluate(() => { window.nameVoice = document.querySelector('.naming-story-audio'); });
  await p.keyboard.press('Escape');
  await p.waitForFunction(() => window.nameVoice.paused);
  await p.locator('.telephone').click();
  await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .1);
  assert.equal(await p.evaluate(() => window.nameVoice.paused), true);
  await p.setViewportSize({ width: 844, height: 390 });
  await p.screenshot({ path: 'docs/qa/last-signal-voice-landscape.png' });
  const progress = await p.locator('.signal-seek').boundingBox();
  assert.ok(progress.x >= 0 && progress.x + progress.width <= 844);
  await p.keyboard.press('Escape');
  await p.setViewportSize({ width: 1440, height: 900 });
  await p.emulateMedia({ reducedMotion: 'no-preference' });
  await p.locator('.telephone').click();
  await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .7);
  const partial = await p.locator('.signal-text').innerText();
  assert.ok(partial.length > 0 && partial.length < stories.sojourner.paragraphs[0].length);
  await p.getByRole('button', { name: 'Pause', exact: true }).click();
  const pausedText = await p.locator('.signal-text').innerText();
  await p.waitForTimeout(350);
  assert.equal(await p.locator('.signal-text').innerText(), pausedText);
  await p.keyboard.press('Escape');
  await p.evaluate(() => {
    window.realMediaPlay = HTMLMediaElement.prototype.play;
    HTMLMediaElement.prototype.play = function () { return this.classList.contains('signal-voice') ? Promise.reject(new DOMException('Autoplay blocked', 'NotAllowedError')) : window.realMediaPlay.call(this); };
  });
  await p.locator('.telephone').click();
  await p.getByRole('button', { name: 'Play narration', exact: true }).waitFor();
  assert.match(await p.locator('.signal-audio-status').innerText(), /Press Play narration/);
  await p.evaluate(() => { HTMLMediaElement.prototype.play = window.realMediaPlay; });
  await p.getByRole('button', { name: 'Play narration', exact: true }).click();
  await p.waitForFunction(() => document.querySelector('.signal-voice')?.currentTime > .1);
  await p.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  await writeFile('docs/qa/last-signal-audio-results.json', JSON.stringify({ passed: true, base, checks: ['Four correct supplied recordings', 'Three automatic Last Signal playbacks', 'CurrentTime-driven paragraph selection and typed words', 'Pause freezes voice and text', 'Seek/Next stay synchronized', 'Mute toggles actual narration', 'No fade while final words are paused', 'Only audio end triggers static and home return', 'Close/skip stop and release old player', 'Naming story autoplay and cleanup', 'Landscape seek control', 'Autoplay-blocked recovery', 'No browser exceptions'], errors }, null, 2));
  console.log('Narration passed: four supplied recordings, media-clock sync, controls, cleanup, ending and autoplay recovery.');
} finally { await browser.close(); }
